"""Build the private corpus and graph from extracted pages, and write reports/corpus.json (numbers only)."""

import json
from collections import Counter
from pathlib import Path

from mathhinter.corpus.graph import build_index, find_references
from mathhinter.corpus.structure import pair_exercises, parse_book

PRIVATE = Path("data/private")


def render(report: dict) -> None:
    refs, check = report["references"], report["hand_check"]
    lines = ["# Corpus structure", "", "Generated by `scripts/build_corpus.py`. Do not edit by hand.", "",
             "| Volume | Pages | Modules | Worked exercise pairs | Definitions | Theorems | Propositions | "
             "End-of-module exercises | Indications |", "|---|---|---|---|---|---|---|---|---|"]
    for number, volume in report["volumes"].items():
        units = volume["units"]
        lines.append(f"| {number} | {volume['pages']} | {volume['modules']} | {volume['exercise_solution_pairs']} | "
                     f"{units.get('definition', 0)} | {units.get('theorem', 0)} | {units.get('proposition', 0)} | "
                     f"{units.get('exercise_end', 0)} | {units.get('indication', 0)} |")
    lines += ["", "## Prerequisite links", "",
              f"- {refs['found']} references with a number and a page found; {refs['linked']} linked "
              f"({100 * refs['linked_share']:.0f}%), {refs['unresolved']} unresolved, "
              f"{refs['external']} to other books.",
              f"- {refs['across_volumes']} linked references cross from one volume to another.",
              f"- {refs['proofs_and_solutions_with_a_link']} of {refs['proofs_and_solutions']} proofs and solutions "
              "contain a link.", "", "## Hand check", "",
              f"- Exercise paired with the right solution: {check['pairs_correct']} of {check['pairs_sampled']}.",
              f"- Solution stops where it should: {check['solutions_ending_cleanly']} of {check['pairs_sampled']}.",
              f"- Link reaches the unit it names: {check['links_correct']} of {check['links_sampled']}.", "",
              "Checked by Claude on random samples, not yet by a person. A clean parse doesn't mean clean formulas: "
              "see the extraction report.", ""]
    Path("reports/corpus.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    records = []
    report: dict = {"volumes": {}}
    pairs_out = []
    for volume in (1, 2, 3):
        pages = [json.loads(line) for line in (PRIVATE / f"pages-v{volume}.jsonl").open(encoding="utf-8")]
        units = parse_book(volume, pages)
        ids = {id(u): f"v{volume}:{i:05d}" for i, u in enumerate(units)}
        records += [(ids[id(u)], u) for u in units]
        kinds = Counter(u.kind for u in units)
        pairs = pair_exercises(units)
        pairs_out += [{"exercise": ids[id(a)], "solution": ids[id(b)]} for a, b in pairs]
        report["volumes"][str(volume)] = {
            "pages": len(pages), "modules": len({u.module for u in units if u.module}),
            "units": dict(sorted(kinds.items())),
            "exercise_solution_pairs": len(pairs), "exercises_without_solution": kinds["exercise"] - len(pairs),
            "solutions_without_exercise": kinds["solution"] - len(pairs),
        }
    by_id = dict(records)
    references = find_references(by_id, build_index(records))
    edges = [{"source": r.source, "target": r.target, "kind": r.kind} for r in references if r.status == "linked"]
    statuses = Counter(r.status for r in references)
    sources = {r.source for r in references if r.status == "linked"}
    argued = [i for i, u in by_id.items() if u.kind in ("proof", "solution")]
    report["references"] = {
        "found": len(references), **dict(sorted(statuses.items())),
        "linked_share": round(statuses["linked"] / len(references), 3),
        "across_volumes": sum(by_id[e["source"]].volume != by_id[e["target"]].volume for e in edges),
        "proofs_and_solutions": len(argued),
        "proofs_and_solutions_with_a_link": sum(i in sources for i in argued),
    }
    with (PRIVATE / "units.jsonl").open("w", encoding="utf-8") as out:
        for ident, unit in records:
            record = unit.record(0)
            record["id"] = ident
            out.write(json.dumps(record, ensure_ascii=False) + "\n")
    (PRIVATE / "pairs.json").write_text(json.dumps(pairs_out), encoding="utf-8")
    (PRIVATE / "edges.json").write_text(json.dumps(edges), encoding="utf-8")
    checks = json.loads(Path("data/hand_checks/structure.json").read_text(encoding="utf-8"))
    pairs_checked, links_checked = checks["exercise_solution_pairs"], checks["links"]
    report["hand_check"] = {
        "pairs_sampled": len(pairs_checked),
        "pairs_correct": sum(p["paired_correctly"] for p in pairs_checked),
        "solutions_ending_cleanly": sum(p["solution_ends_cleanly"] for p in pairs_checked),
        "links_sampled": len(links_checked),
        "links_correct": sum(p["correct"] for p in links_checked),
    }
    report["totals"] = {
        "pages": sum(v["pages"] for v in report["volumes"].values()),
        "exercise_solution_pairs": sum(v["exercise_solution_pairs"] for v in report["volumes"].values()),
    }
    Path("reports/corpus.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    render(report)
    print(json.dumps(report, indent=1))


if __name__ == "__main__":
    main()
