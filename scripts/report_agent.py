"""Render reports/agent.md from reports/agent.json and the hand checks."""

import json
from pathlib import Path

LABELS = {"llm_only": "LLM alone", "rag": "RAG", "agent": "Agent (search and checker)",
          "rag_leak": "RAG, solution not hidden"}


def main() -> None:
    report = json.loads(Path("reports/agent.json").read_text(encoding="utf-8"))
    hand = json.loads(Path("data/hand_checks/agent.json").read_text(encoding="utf-8"))
    hints, cites, alarms = hand["hints"], hand["citations"], hand["false_alarms"]
    usage = report["agent_usage"]
    lines = ["# Tutor evaluation", "", "Generated by `scripts/report_agent.py`. Do not edit by hand.", "",
             f"Model `{report['model']}` on {report['exercises']} exercises from the test modules, each with a wrong "
             "attempt holding one known error and an unchanged control. Prompts were fixed on development exercises "
             "before this run.", "",
             "**Both right** means the exact wrong line was found and the control was left alone.", "",
             "| Version | Both right (95% CI) | Exact line | Error flagged | False alarm | Invalid reply | "
             "Tokens per review |", "|---|---|---|---|---|---|---|"]
    for key, label in LABELS.items():
        row = report["configs"][key]
        low, high = row["both_right_ci95"]
        lines.append(f"| {label} ({row['exercises']} exercises) | {row['both_right']:.2f} ({low:.2f}-{high:.2f}) | "
                     f"{row['exact_line']:.2f} | {row['error_flagged']:.2f} | {row['false_alarm']:.2f} | "
                     f"{row['invalid']:.2f} | {row['tokens_per_review']} |")
    agent = report["agent_minus_llm_only"]
    rag = report["rag_minus_llm_only"]
    lines += ["", f"Guessing a line at random would find the exact line {report['chance_exact_line']:.2f} of the time.",
              "", "## Differences", "",
              f"- RAG minus LLM alone: {rag['difference']:+.2f} "
              f"(95% CI {rag['ci95'][0]:+.2f} to {rag['ci95'][1]:+.2f}).",
              f"- Agent minus LLM alone: {agent['difference']:+.2f} (95% CI {agent['ci95'][0]:+.2f} to "
              f"{agent['ci95'][1]:+.2f}).", "",
              "## How the agent behaved", "",
              f"- It searched {usage['searches']} times and never called the equality checker.",
              f"- All {usage['citations']} of its citations named passages it had been shown.",
              f"- {report['configs']['agent']['failures'].get('api', 0)} agent reviews failed because Groq rejected "
              "a reply in which the model tried to call a tool natively. Even if all of them had been right, the "
              "agent would only tie LLM alone.",
              "- No version was ever shown the exercise's own solution, including the variant that didn't hide it, "
              "so the leak check measured nothing here.", "",
              "## Hand checks", "",
              f"- Hints pointing at the error: {sum(h['points_at_the_error'] for h in hints)} of {len(hints)}. "
              f"Nearly giving the answer away: {sum(h['nearly_gives_the_answer'] for h in hints)}. "
              f"Stating the correction outright: {sum(h['states_the_correction'] for h in hints)}.",
              f"- Citations supporting the judgement: {sum(c['supports'] for c in cites)} of {len(cites)}. The rest "
              "are on the topic but not what the explanation relies on.",
              f"- False alarms on controls: {alarms['from_garbled_extraction']} of {alarms['read']} came from "
              "garbled extraction. Most others dispute the book's own reasoning, sometimes over a real edge case.",
              "", "Read by Claude, not yet by a person. With 25 exercises, differences under about 0.2 can't be "
              "told apart from chance.", ""]
    Path("reports/agent.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
