"""Render reports/evalset.md from the JSON reports."""

import json
from pathlib import Path

REASONS = {"kept": "Kept", "broken_formula": "Broken formula", "needs_earlier_context": "Needs earlier context",
           "stray_formula_fragment": "Stray formula fragment", "too_short": "Too short",
           "unbalanced_formula": "Unbalanced formula", "unreadable_characters": "Unreadable characters",
           "solution_too_short": "Solution too short"}


def main() -> None:
    evalset = json.loads(Path("reports/evalset.json").read_text(encoding="utf-8"))
    checker = json.loads(Path("reports/checker.json").read_text(encoding="utf-8"))
    hand = evalset["hand_check"]
    book = checker["book_equalities"]
    wrong = checker["corrupted_copies_of_verified"]
    lines = ["# Test set and checker", "", "Generated by `scripts/report_evalset.py`. Do not edit by hand.", "",
             f"## Exercises ({evalset['exercises']} worked exercises)", "", "| Outcome | Count |", "|---|---|"]
    lines += [f"| {REASONS[k]} | {v} |" for k, v in evalset["outcome"].items()]
    lines += ["", f"Of those kept, {evalset['kept_by_split']['test']} are in the test modules and "
              f"{evalset['kept_by_split']['dev']} in development modules; "
              f"{evalset['kept_by_type']['computation']} ask for a computation and "
              f"{evalset['kept_by_type']['proof_or_other']} are proofs or other tasks.", "",
              f"In a hand check, {hand['kept_usable']} of {hand['kept_sampled']} kept exercises were readable and "
              "answerable alone. The filter misses context like \"En déduire\" and some garbled words.", "",
              "## Wrong attempts", "", "| Kind of error | Attempts |", "|---|---|"]
    lines += [f"| {k.replace('_', ' ')} | {v} |" for k, v in evalset["attempts_by_kind"].items() if k != "none"]
    controls = evalset["attempts_by_kind"]["none"]
    lines += ["", f"Each kept exercise also has an unchanged control ({controls} in all), so "
              "a detector that always cries wrong scores badly.", "",
              f"In a hand check, {hand['corrupted_really_wrong']} of {hand['corrupted_sampled']} edits made a false "
              "statement. The rest landed in garbled formulas or only weakened a claim. Later lines still follow the "
              "correct solution, unlike a real student's errors.", "",
              "## Checker", "", f"Run once on {checker['equalities']} equalities from solutions and proofs in the "
              "test modules, after being frozen on the development modules.", "",
              "| Book equalities | Count |", "|---|---|",
              f"| vérifié | {book['vérifié']} |", f"| réfuté | {book['réfuté']} |",
              f"| non vérifiable | {book['non vérifiable']} |", "", "| Why not verified | Count |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in checker["why_unverifiable"].items()
              if k not in ("identity", "same number")]
    judged = json.loads(Path("data/hand_checks/checker.json").read_text(encoding="utf-8"))
    lines += ["", f"Corrupted copies of verified equalities: {wrong['tested']} tested, {wrong['still_verified']} still "
              f"verified, {wrong['refuted']} refuted, {wrong['unverifiable']} no longer verified. The ones still "
              "verified were harmless, such as changing a power of 1.", "",
              "### Can a verdict be trusted?", "",
              f"- **vérifié:** {judged['sound']} of {judged['verified']} were sound when read by hand. "
              "The others treat group elements or endomorphisms as commuting numbers, "
              "or an inverse image as an inverse.",
              f"- **réfuté:** all {book['réfuté']} on these correct book equalities were false alarms, from notation "
              "such as Legendre symbols or garbled tables. So it means \"read this again\", not \"this is wrong\".",
              "- Two parser fixes came from reading this same sample, and the run was repeated, so this isn't a "
              "fully untouched test. Both only make the checker more cautious.", ""]
    Path("reports/evalset.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
