"""Render reports/extraction.md from reports/extraction.json."""

import json
from pathlib import Path

LABELS = {"poppler": "Poppler `pdftotext`", "font_symbols_no_layout": "Our glyph names, no layout",
          "font_aware": "Our font-aware extractor", "pix2tex": "pix2tex (image OCR)"}


def section(title: str, data: dict) -> list[str]:
    lines = [f"## {title}", "", f"{data['scored']} of {data['formulas_sampled']} sampled formulas scored; "
             f"{data['excluded_detection_errors']} had crops that were cut off or merged with other content.", "",
             "| Tool | Token similarity (95% CI) | Symbols only | Exact | Vol. 1 | Vol. 2 | Vol. 3 |",
             "|---|---|---|---|---|---|---|"]
    for name, row in data["per_tool"].items():
        low, high = row["structure_ci95"]
        by = row["by_volume_structure"]
        lines.append(f"| {LABELS.get(name, name)} | {row['structure_similarity']:.3f} ({low:.3f}-{high:.3f}) | "
                     f"{row['symbol_similarity']:.3f} | {100 * row['exact_share']:.0f}% | "
                     f"{by['1']:.3f} | {by['2']:.3f} | {by['3']:.3f} |")
    return [*lines, "", f"Gold file SHA-256: `{data['gold_sha256']}`", ""]


def main() -> None:
    report = json.loads(Path("reports/extraction.json").read_text())
    text = ["# Formula extraction", "", "Generated by `scripts/report_extraction.py`. Do not edit by hand.", "",
            "Similarity is 1 minus the normalised token edit distance to a transcription made from the page image.",
            "Exact means every token matches after canonicalisation, which ignores braces and spacing.", ""]
    text += section("Held-out test set", report["test"])
    text += ["## How to read this", "",
             "- This sample was drawn after the code was frozen. Earlier samples were used for development.",
             "- The transcriptions were made by Claude from page images, before seeing outputs for the test set. "
             "They have not yet been fully checked by a person.",
             "- Scored formulas exclude crops the detector got wrong, which are often matrices and multi-line "
             "displays, so these scores are likely optimistic for those layouts.",
             "- Book text can't be published, so the gold files stay private. The hash identifies the version used.",
             "- A similarity score is not correctness. One wrong symbol can change the mathematics, so the exact "
             "share matters more for checking answers.", ""]
    Path("reports/extraction.md").write_text("\n".join(text), encoding="utf-8")


if __name__ == "__main__":
    main()
