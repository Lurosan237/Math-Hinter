"""Report the pipeline's single run on the 25 test exercises against the stage 4 configurations.

    PYTHONPATH=src python scripts/report_pipeline.py

Reads data/private/agent_runs/test and data/private/agent_runs/pipeline-test (private), writes
reports/pipeline.json and reports/pipeline.md (numbers only).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from mathhinter.agent.scoring import difference_interval, proportion_interval, summarise  # noqa: E402

RUNS = ROOT / "data/private/agent_runs"
NAMES = {"llm_only": "LLM alone", "rag": "RAG", "agent": "Agent", "pipeline": "Pipeline (check first, judge second)"}


def load(name: str) -> list[dict]:
    return [json.loads(line) for line in (RUNS / name / "reviews.jsonl").read_text(encoding="utf-8").splitlines()]


def before_second_opinion(rows: list[dict]) -> list[dict]:
    """The pipeline's reviews as the judge left them, putting back flags the second opinion withdrew."""
    restored = []
    for row in rows:
        if row.get("rejected"):
            row = {**row, "verdict": "wrong", "first_wrong_line": row["rejected"]["line"]}
        restored.append(row)
    return restored


def main() -> None:
    stage4 = load("test")
    rows = {c: [r for r in stage4 if r["config"] == c] for c in ("llm_only", "rag", "agent")}
    rows["pipeline"] = load("pipeline-test")
    judge_only = before_second_opinion(rows["pipeline"])
    pipeline = rows["pipeline"]
    checks = [c for r in pipeline for c in r.get("checks", [])]
    withdrawn = [r for r in pipeline if r.get("rejected")]
    report = {
        "exercises": len({r["exercise"] for r in pipeline}),
        "configs": {c: {**summarise(r), "both_right_ci95": proportion_interval(r)} for c, r in rows.items()},
        "pipeline_minus_llm_only": difference_interval(pipeline, rows["llm_only"]),
        "second_opinion": {
            "withdrawn": len(withdrawn),
            "withdrawn_true_errors": sum(1 for r in withdrawn
                                         if r["kind"] != "none" and r["rejected"]["line"] == r["wrong_line"]),
            "withdrawn_false_alarms": sum(1 for r in withdrawn if r["kind"] == "none"),
            "judge_alone_post_hoc": summarise(judge_only),
        },
        "computation": {"claims_checked": len(checks),
                        "verified": sum(c["status"] == "vérifié" for c in checks),
                        "refuted": sum(c["status"] == "réfuté" for c in checks)},
        "tokens_per_review": round(sum(r["tokens"] for r in pipeline) / len(pipeline)),
    }
    (ROOT / "reports/pipeline.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    write_markdown(report)


def pct(x: float) -> str:
    return f"{x:.2f}"


def write_markdown(r: dict) -> None:
    lines = ["# Pipeline evaluation", "", "Generated by `scripts/report_pipeline.py`. Do not edit by hand.", "",
             f"One run of the frozen pipeline (`docs/pipeline.md`) on the same {r['exercises']} test exercises as "
             "the stage 4 evaluation (`reports/agent.md`), each with a wrong attempt and an unchanged control. The "
             "pipeline was designed on development exercises only.", "",
             "| Version | Both right (95% CI) | Exact line | Error flagged | False alarm | Invalid reply |",
             "|---|---|---|---|---|---|"]
    for key, s in r["configs"].items():
        lo, hi = s["both_right_ci95"]
        lines.append(f"| {NAMES[key]} | {pct(s['both_right'])} ({pct(lo)}-{pct(hi)}) | {pct(s['exact_line'])} | "
                     f"{pct(s['error_flagged'])} | {pct(s['false_alarm'])} | {pct(s['invalid'])} |")
    d = r["pipeline_minus_llm_only"]
    o = r["second_opinion"]
    j = o["judge_alone_post_hoc"]
    c = r["computation"]
    lines += ["", f"Pipeline minus LLM alone: {d['difference']:+.2f} (95% CI {d['ci95'][0]:+.2f} to "
              f"{d['ci95'][1]:+.2f}). The pipeline did worse.", "",
              "## Why", "",
              f"- The second opinion withdrew {o['withdrawn']} flags: {o['withdrawn_true_errors']} were the planted "
              f"error on the right line, {o['withdrawn_false_alarms']} were false alarms on controls. It cut false "
              "alarms, but it threw away more real errors than wrong ones.",
              f"- Read after the fact, the judge alone (flags put back) would have found the exact line "
              f"{pct(j['exact_line'])} of the time with {pct(j['false_alarm'])} false alarms, both right "
              f"{pct(j['both_right'])}. This was not the frozen design, so it is not a test result.",
              f"- The computer checked {c['claims_checked']} claims on these PDF-extracted textbook solutions and "
              f"could verify {c['verified']} and refute {c['refuted']}: almost no evidence for the judge.",
              f"- {r['tokens_per_review']} tokens per review, against about 1600 for LLM alone.", "",
              "With 25 exercises, differences under about 0.2 can't be told apart from chance. The test set has now "
              "been used twice; any further change is exploratory until new test data exists (real student "
              "attempts)."]
    (ROOT / "reports/pipeline.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
