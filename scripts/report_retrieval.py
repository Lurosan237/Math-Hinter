"""Render reports/retrieval.md from the JSON reports."""

import json
from pathlib import Path

LABELS = [("nearby_units", "Nearest earlier units in the book"), ("word_vectors", "Word vectors"),
          ("bm25_words", "BM25, words"), ("bm25_words_math", "BM25, words and maths symbols"),
          ("bm25_results_only", "BM25 over definitions and results only"),
          ("bm25_section_titles", "... plus section titles"),
          ("bm25_titles_plus_nearby", "... plus position in the book")]


def main() -> None:
    report = json.loads(Path("reports/retrieval.json").read_text(encoding="utf-8"))
    cross = json.loads(Path("reports/crosslinks.json").read_text(encoding="utf-8"))
    leak = report["own_solution_if_not_hidden"]
    far = report["other_module"]
    lines = ["# Retrieval", "", "Generated by `scripts/report_retrieval.py`. Do not edit by hand.", "",
             "The labels come from the books: when a proof or solution cites a numbered result, that statement is the",
             "query and the cited result is the right answer. A test split of whole modules was run once, after the",
             "settings were chosen on the other split.", "",
             f"{report['questions']} questions, {report['gold_links']} cited results. Each question hides its own "
             "statement and solution or proof.", "",
             "| Ranker | Recall@5 (95% CI) | Recall@10 | Recall@50 | MRR (95% CI) |", "|---|---|---|---|---|"]
    for key, label in LABELS:
        row = report["all"][key]
        low, high = row["recall_5_ci95"]
        mlow, mhigh = row["mrr_ci95"]
        lines.append(f"| {label} | {row['recall_5']:.3f} ({low:.3f}-{high:.3f}) | {row['recall_10']:.3f} | "
                     f"{row['recall_50']:.3f} | {row['mrr']:.3f} ({mlow:.3f}-{mhigh:.3f}) |")
    source = report["by_source"]
    lines += ["", "## Where it's weak", "",
              f"- Results from another module ({far['questions']} questions): recall@10 is "
              f"{far['rankers']['bm25_results_only']['recall_10']:.3f} for search alone and "
              f"{far['rankers']['bm25_titles_plus_nearby']['recall_10']:.3f} once position in the book is added.",
              f"- Exercises make up only {source['exercise']['questions']} of the questions; the other "
              f"{source['result']['questions']} are statements of results.",
              "- A citation is only one right answer. Other useful passages count as misses, "
              "so these are lower bounds.",
              "- Position in the book only exists for exercises from the book, not for a student's own question.",
              "", "## The leak", "",
              f"If each exercise's own solution weren't hidden, search would return it first for "
              f"{100 * leak['top_1']:.0f}% of {leak['exercises']} exercises and in the top 5 for "
              f"{100 * leak['top_5']:.0f}%.", "", "## Cross-volume links", "",
              "None of the books' numbered references cross volumes, "
              "so these links come from earlier volumes' indexes:",
              "a term in a statement leads to the definition on the page the index gives.", ""]
    for volume, row in cross["volumes"].items():
        lines.append(f"- Volume {volume}: {row['statements_with_a_link']} of {row['statements']} worked exercises "
                     f"get a link, from {row['terms']} usable terms.")
    index, search = cross["hand_check"]["index"], cross["hand_check"]["search"]
    lines += ["", "| Method | Statement really uses the linked concept | 95% CI |", "|---|---|---|",
              f"| Index terms | {index['uses_the_concept']} of {index['sampled']} | "
              f"{index['ci95'][0]:.2f}-{index['ci95'][1]:.2f} |",
              f"| Search over earlier definitions | {search['uses_the_concept']} of {search['sampled']} | "
              f"{search['ci95'][0]:.2f}-{search['ci95'][1]:.2f} |", "",
              "Judged by Claude from a shuffled sample with the method hidden, not yet by a person. A correct link "
              "isn't necessarily the one a student is missing: many point at basics such as what a matrix is.", ""]
    Path("reports/retrieval.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
