"""Ask for the second and third hints on each example attempt with a planted error, for checking by hand that no
hint gives the answer away. Writes reports/hints.md and reports/hints.json; the verdicts go in
data/hand_checks/hints.json.

    PYTHONPATH=src python scripts/sample_hints.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from mathhinter.agent.course import CourseSearch  # noqa: E402
from mathhinter.agent.tutor import Tutor  # noqa: E402
from mathhinter.hints import HINT_MODEL, next_hint  # noqa: E402
from mathhinter.llm.client import Client, read_env  # noqa: E402
from mathhinter.web import MODEL  # noqa: E402


def main() -> None:
    client = Client(read_env(ROOT / ".env")["GROQ_API_KEY"], ROOT / "data/private/llm_cache")
    units = json.loads((ROOT / "site/data/corpus.json").read_text(encoding="utf-8"))["units"]
    by_id = {u["id"]: u for u in units}
    tutor = Tutor(client, MODEL, CourseSearch(units))
    rows = []
    for exercise in json.loads((ROOT / "data/demo/exercises.json").read_text(encoding="utf-8"))["exercises"]:
        attempt = exercise["attempts"][0]
        review = tutor.rag(exercise["statement"], attempt["text"], "web", solution="")
        row = {"exercise": exercise["id"], "title": exercise["title"], "planted_line": attempt["wrong_line"],
               "flagged_line": review.first_wrong_line, "hints": [review.hint]}
        if review.verdict == "wrong" and review.hint:
            passages = [{"label": by_id[i].get("label", i), "text": by_id[i]["text"][:1200]}
                        for i in review.citations[:3] if i in by_id]
            for _ in range(2):
                row["hints"].append(next_hint(client, exercise["statement"], attempt["text"],
                                              review.first_wrong_line, row["hints"], review.explanation, passages))
        rows.append(row)
        print(exercise["id"], len(row["hints"]))
    (ROOT / "reports/hints.json").write_text(json.dumps({"model": HINT_MODEL, "rows": rows}, ensure_ascii=False,
                                                        indent=1) + "\n", encoding="utf-8")
    lines = ["# Further hints", "", "Generated by `scripts/sample_hints.py`: the review's hint, then the second and "
             "third hints, for each example attempt with a planted error. Whether any hint gives the answer away "
             "is judged by hand in `data/hand_checks/hints.json`.", ""]
    for row in rows:
        lines += [f"## {row['title']} (`{row['exercise']}`)", "",
                  f"Planted error on line {row['planted_line']}; the review flagged line {row['flagged_line']}.", ""]
        lines += [f"{i}. {hint}" for i, hint in enumerate(row["hints"], 1)] + [""]
    (ROOT / "reports/hints.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
